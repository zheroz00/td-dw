test('recap: YouTube with no captions does not fall back to memory', async () => {
  const env = serviceFor({ youtube: fakeYouTube({ captions: null }) });
  const record = await env.service.recap(YT_HINT);
  assertNotRecapped(env, record, "TD;DW found no captions up to this point in the video, so there's nothing to recap yet.");
});

test('recap: a YouTube request error is a failed result, logged, with no LLM call', async () => {
  for (const opts of [{ findError: new Error('YouTube search failed (429)') }, { transcriptError: new Error('innertube player failed (403)') }]) {
    const warnings = [];
    const env = serviceFor({ youtube: fakeYouTube(opts) });
    const service = createRecapService({ jellyfin: env.jf, youtube: env.youtube, config, engine: env.engine, log: { warn: (m) => warnings.push(m) } });
    const record = await service.recap(YT_HINT);
    const reason = (opts.findError || opts.transcriptError).message;
    assert.deepEqual(record.result, { ok: false, error: `Couldn't reach YouTube (${reason}).` });
    assert.equal(env.engine.seen.videoState, undefined);
    assert.equal(warnings.length, 1);
    assert.match(warnings[0], new RegExp(reason.replace(/[()]/g, '\\$&')));
  }
});

test('recap: a known unsupported app gets a plain message, no pause, no LLM, no Jellyfin', async () => {
  const env = serviceFor();
  const record = await env.service.recap({ nowPlaying: { app: 'com.netflix.ninja', title: 'Stranger Things', artist: null, positionMs: 125000, durationMs: null }, mediaAccess: null });
  assertNotRecapped(env, record, "TD;DW on the TV doesn't support Netflix yet. It works with Jellyfin and YouTube.");
  assert.equal(record.videoState.service, 'Netflix');
  assert.equal(record.videoState.title, 'Netflix');
  assert.equal(record.videoState.currentTimeSeconds, 125);
  assert.deepEqual(env.jf.calls, []);
  assert.deepEqual(env.youtube.calls, []);
});

