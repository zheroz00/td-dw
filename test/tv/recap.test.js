import { test } from 'node:test';
import assert from 'node:assert/strict';
import { describeItem, loadTranscript, createRecapService } from '../../tv/lib/recap.js';
import { loadConfig } from '../../tv/lib/config.js';

const ENV = {
  JELLYFIN_URL: 'http://jellyfin.local:8096',
  JELLYFIN_API_KEY: 'k',
  TDDW_TV_KEY: 'abcdef0123456789abcdef',
  LLM_BASE_URL: 'http://llm.local/v1',
  LLM_MODEL: 'm'
};
const config = loadConfig(ENV);

const VTT = [
  'WEBVTT', '',
  '00:00:05.000 --> 00:00:07.000', 'Hello from the start.', '',
  '00:10:00.000 --> 00:10:02.000', 'Ten minutes in.', '',
  '00:50:00.000 --> 00:50:02.000', 'A spoiler from later.'
].join('\n');

const textSub = (Index) => ({ Type: 'Subtitle', IsTextSubtitleStream: true, Index, Language: 'eng' });

const MOVIE = {
  Id: 'movie1',
  Type: 'Movie',
  Name: 'Matchbox',
  RunTimeTicks: 6000 * 1e7,
  MediaSources: [
    { Id: 'src-a', MediaStreams: [textSub(2)] },
    { Id: 'src-b', MediaStreams: [textSub(5)] }
  ]
};

const LIVE_SESSION = {
  Id: 's-tv',
  UserId: 'u1',
  LastActivityDate: '2026-10-12T10:00:00Z',
  NowPlayingItem: { Id: 'movie1', MediaType: 'Video' },
  PlayState: { PositionTicks: 900 * 1e7, MediaSourceId: 'src-b' }
};

function fakeJellyfin(opts = {}) {
  const calls = [];
  return {
    calls,
    async getSessions() { return opts.sessions ?? [LIVE_SESSION]; },
    async getItem() { return opts.item ?? MOVIE; },
    async getResumeItem() { return opts.resume ?? null; },
    async getSubtitleVtt(itemId, sourceId, index) {
      calls.push(`vtt ${itemId} ${sourceId} ${index}`);
      if (opts.vttError) throw opts.vttError;
      return VTT;
    },
    async pause(sessionId) {
      calls.push(`pause ${sessionId}`);
      if (opts.pauseError) throw opts.pauseError;
    }
  };
}

function fakeEngine(result = { ok: true, known: true, recapText: '- [0:05] Hello.', source: 'transcript' }) {
  const seen = {};
  return {
    seen,
    async recap(videoState, llm) { seen.videoState = videoState; seen.llm = llm; return result; },
    async answer(messages, llm) { seen.messages = messages; seen.llm = llm; return 'An answer.'; }
  };
}

const quietLog = { warn() {} };

test('describeItem: a movie', () => {
  assert.deepEqual(describeItem(MOVIE, 900), {
    service: 'Jellyfin',
    title: 'Matchbox',
    episodeInfo: null,
    currentTimeSeconds: 900,
    durationSeconds: 6000
  });
});

test('describeItem: an episode, with and without numbers', () => {
  const ep = { Type: 'Episode', SeriesName: 'Severance', ParentIndexNumber: 1, IndexNumber: 2, Name: 'Half Loop' };
  assert.equal(describeItem(ep, 0).title, 'Severance');
  assert.equal(describeItem(ep, 0).episodeInfo, 'S1:E2 - Half Loop');
  assert.equal(describeItem({ Type: 'Episode', SeriesName: 'X' }, 0).episodeInfo, 'S?:E?');
  assert.equal(describeItem({ Type: 'Episode', SeriesName: 'X' }, 0).durationSeconds, null);
});

test('loadTranscript: uses the media source that is playing and stops at the position', async () => {
  const jf = fakeJellyfin();
  const t = await loadTranscript(jf, MOVIE, { mediaSourceId: 'src-b', positionSeconds: 900, subtitleLang: 'en', transcriptBudget: 'standard' });
  assert.deepEqual(jf.calls, ['vtt movie1 src-b 5']);
  assert.match(t.text, /Ten minutes in\./);
  assert.doesNotMatch(t.text, /spoiler/);
  assert.equal(t.autoGenerated, false);
  assert.equal(t.truncated, false);
  assert.equal(t.language, 'eng');
});

test('loadTranscript: an unknown media source falls back to the first one', async () => {
  const jf = fakeJellyfin();
  await loadTranscript(jf, MOVIE, { mediaSourceId: null, positionSeconds: 900, subtitleLang: 'en', transcriptBudget: 'standard' });
  assert.deepEqual(jf.calls, ['vtt movie1 src-a 2']);
});

test('loadTranscript: image-only subtitles mean no transcript and no download', async () => {
  const jf = fakeJellyfin();
  const item = { ...MOVIE, MediaSources: [{ Id: 'src-a', MediaStreams: [{ Type: 'Subtitle', IsTextSubtitleStream: false, Index: 3 }] }] };
  assert.equal(await loadTranscript(jf, item, { mediaSourceId: null, positionSeconds: 900, subtitleLang: 'en', transcriptBudget: 'standard' }), null);
  assert.deepEqual(jf.calls, []);
});

test('loadTranscript: a position before the first cue means no transcript', async () => {
  const t = await loadTranscript(fakeJellyfin(), MOVIE, { mediaSourceId: 'src-b', positionSeconds: 2, subtitleLang: 'en', transcriptBudget: 'standard' });
  assert.equal(t, null);
});

test('recap: pauses the live session and hands the engine a grounded videoState', async () => {
  const jf = fakeJellyfin();
  const engine = fakeEngine();
  const record = await createRecapService({ jellyfin: jf, config, engine, log: quietLog }).recap();
  assert.ok(jf.calls.includes('pause s-tv'));
  assert.equal(engine.seen.llm, config.llm);
  assert.equal(engine.seen.videoState.title, 'Matchbox');
  assert.equal(engine.seen.videoState.currentTimeSeconds, 900);
  assert.match(engine.seen.videoState.transcript.text, /Ten minutes in\./);
  assert.equal(typeof record.id, 'string');
  assert.ok(!Number.isNaN(Date.parse(record.createdAt)));
  assert.deepEqual(record.result, { ok: true, known: true, recapText: '- [0:05] Hello.', source: 'transcript' });
  assert.equal(record.fromResumePoint, false);
  assert.equal(record.subtitleNote, null);
  assert.deepEqual(record.history, []);
});

test('recap: PAUSE_ON_RECAP=false leaves the TV playing', async () => {
  const jf = fakeJellyfin();
  const noPause = loadConfig({ ...ENV, PAUSE_ON_RECAP: 'false' });
  await createRecapService({ jellyfin: jf, config: noPause, engine: fakeEngine(), log: quietLog }).recap();
  assert.ok(!jf.calls.some((c) => c.startsWith('pause')));
});

test('recap: a resume point is labelled and nothing is paused', async () => {
  const jf = fakeJellyfin({
    sessions: [{ Id: 's-tv', UserId: 'u1', LastActivityDate: '2026-10-12T10:00:00Z' }],
    resume: { Id: 'movie1', UserData: { PlaybackPositionTicks: 900 * 1e7 } }
  });
  const record = await createRecapService({ jellyfin: jf, config, engine: fakeEngine(), log: quietLog }).recap();
  assert.equal(record.fromResumePoint, true);
  assert.ok(!jf.calls.some((c) => c.startsWith('pause')));
});

test('recap: a failed pause does not block the recap', async () => {
  const jf = fakeJellyfin({ pauseError: new Error('session gone') });
  const record = await createRecapService({ jellyfin: jf, config, engine: fakeEngine(), log: quietLog }).recap();
  assert.equal(record.result.ok, true);
});

test('recap: a subtitle failure falls back to memory and says so', async () => {
  const jf = fakeJellyfin({ vttError: new Error('Jellyfin GET /Videos failed (500)') });
  const engine = fakeEngine({ ok: true, known: true, recapText: '- Hi.', source: 'knowledge' });
  const record = await createRecapService({ jellyfin: jf, config, engine, log: quietLog }).recap();
  assert.equal(engine.seen.videoState.transcript, null);
  assert.match(record.subtitleNote, /Couldn't load the subtitles .*from memory/);
});

test('ask: sends the recap, the thread so far and the new question', async () => {
  const engine = fakeEngine();
  const service = createRecapService({ jellyfin: fakeJellyfin(), config, engine, log: quietLog });
  const record = await service.recap();
  record.history.push({ question: 'Who is Mark?', answer: 'The lead.' });
  assert.equal(await service.ask(record, 'And the boss?'), 'An answer.');
  const contents = engine.seen.messages.map((m) => m.content);
  assert.equal(contents.at(-1), 'And the boss?');
  assert.ok(contents.includes('Who is Mark?'));
  assert.ok(contents.includes('The lead.'));
  assert.ok(contents.some((c) => c.includes('- [0:05] Hello.')));
  assert.equal(engine.seen.llm, config.llm);
});
