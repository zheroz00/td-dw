import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  isNoKnowledge,
  stripNoKnowledge,
  formatTime,
  buildRecapMessages,
  buildTranscriptMessages,
  buildQuestionMessages
} from '../background/providers/prompts.js';

const baseVideoState = {
  service: 'YouTube',
  title: 'Some Show',
  episodeInfo: null,
  currentTimeSeconds: 600,
  durationSeconds: 1200
};

// --- isNoKnowledge -----------------------------------------------------

test('isNoKnowledge: plain token', () => {
  assert.equal(isNoKnowledge('NO_KNOWLEDGE I have never heard of this.'), true);
});

test('isNoKnowledge: bulleted', () => {
  assert.equal(isNoKnowledge('- NO_KNOWLEDGE I have never heard of this.'), true);
});

test('isNoKnowledge: bolded/markdown-wrapped', () => {
  assert.equal(isNoKnowledge('- **NO_KNOWLEDGE** I have never heard of this.'), true);
});

test('isNoKnowledge: trailing period right after the token', () => {
  assert.equal(isNoKnowledge('NO_KNOWLEDGE.'), true);
});

test('isNoKnowledge: negative — a recap whose second line merely mentions the token', () => {
  const text = '- She starts her new job.\n- Her coworker mentions NO_KNOWLEDGE in passing.';
  assert.equal(isNoKnowledge(text), false);
});

// --- stripNoKnowledge ----------------------------------------------------

test('stripNoKnowledge: strips the bare token and leading punctuation', () => {
  assert.equal(stripNoKnowledge('NO_KNOWLEDGE. I have never heard of this.'), 'I have never heard of this.');
});

test('stripNoKnowledge: strips bulleted + bolded wrapping', () => {
  assert.equal(
    stripNoKnowledge('- **NO_KNOWLEDGE** I have never heard of this title.'),
    'I have never heard of this title.'
  );
});

test('stripNoKnowledge: empty explanation after the token yields empty string', () => {
  assert.equal(stripNoKnowledge('NO_KNOWLEDGE'), '');
});

// --- formatTime ------------------------------------------------------------

test('formatTime: under a minute', () => {
  assert.equal(formatTime(59), '0:59');
});

test('formatTime: exactly one hour', () => {
  assert.equal(formatTime(3600), '1:00:00');
});

test('formatTime: non-finite input', () => {
  assert.equal(formatTime(NaN), 'an unknown time');
});

// --- buildRecapMessages ------------------------------------------------------

test('buildRecapMessages: mentions the cutoff time and the NO_KNOWLEDGE rule, no transcript', () => {
  const messages = buildRecapMessages(baseVideoState, { summaryLength: 'medium' });
  const system = messages[0].content;
  assert.match(system, /10:00/); // 600s -> 10:00
  assert.match(system, /NO_KNOWLEDGE/);
  assert.equal(messages.every((m) => !/transcript/i.test(m.content)), true);
});

test('buildRecapMessages: bullet counts per summaryLength', () => {
  const short = buildRecapMessages(baseVideoState, { summaryLength: 'short' });
  const medium = buildRecapMessages(baseVideoState, { summaryLength: 'medium' });
  const detailed = buildRecapMessages(baseVideoState, { summaryLength: 'detailed' });
  assert.match(short[0].content, /3-5/);
  assert.match(medium[0].content, /5-8/);
  assert.match(detailed[0].content, /8-12/);
});

// --- buildTranscriptMessages -------------------------------------------------

test('buildTranscriptMessages: human-captions wording when autoGenerated is false', () => {
  const videoState = { ...baseVideoState, transcript: { text: '[0:01] hi', autoGenerated: false, truncated: false } };
  const messages = buildTranscriptMessages(videoState, { summaryLength: 'medium' });
  assert.match(messages[0].content, /Stay faithful to the transcript/);
  assert.doesNotMatch(messages[0].content, /auto-generated/);
});

test('buildTranscriptMessages: auto-generated wording when autoGenerated is true', () => {
  const videoState = { ...baseVideoState, transcript: { text: '[0:01] hi', autoGenerated: true, truncated: false } };
  const messages = buildTranscriptMessages(videoState, { summaryLength: 'medium' });
  assert.match(messages[0].content, /auto-generated/);
});

test('buildTranscriptMessages: truncated note only appears when truncated', () => {
  const truncated = { ...baseVideoState, transcript: { text: '[0:01] hi', autoGenerated: true, truncated: true } };
  const notTruncated = { ...baseVideoState, transcript: { text: '[0:01] hi', autoGenerated: true, truncated: false } };
  const truncatedMessages = buildTranscriptMessages(truncated, { summaryLength: 'medium' });
  const notTruncatedMessages = buildTranscriptMessages(notTruncated, { summaryLength: 'medium' });
  assert.match(truncatedMessages[0].content, /evenly sampled to fit/);
  assert.doesNotMatch(notTruncatedMessages[0].content, /evenly sampled to fit/);
});

test('buildTranscriptMessages: transcript text lands in the user message', () => {
  const videoState = {
    ...baseVideoState,
    transcript: { text: '[0:01] a very specific line of dialogue', autoGenerated: true, truncated: false }
  };
  const messages = buildTranscriptMessages(videoState, { summaryLength: 'medium' });
  const user = messages.find((m) => m.role === 'user');
  assert.match(user.content, /a very specific line of dialogue/);
});

// --- buildQuestionMessages -----------------------------------------------

test('buildQuestionMessages: spoiler rules present when spoilerFreeAnswers is true', () => {
  const messages = buildQuestionMessages(baseVideoState, { spoilerFreeAnswers: true }, 'recap text', [], 'who is that?');
  assert.match(messages[0].content, /SPOILER RULES/);
});

test('buildQuestionMessages: spoiler rules absent when spoilerFreeAnswers is false', () => {
  const messages = buildQuestionMessages(baseVideoState, { spoilerFreeAnswers: false }, 'recap text', [], 'who is that?');
  assert.doesNotMatch(messages[0].content, /SPOILER RULES/);
  assert.match(messages[0].content, /COMPLETE answers/);
});

test('buildQuestionMessages: history sliding window keeps only the last 10 turns', () => {
  const history = Array.from({ length: 15 }, (_, i) => ({ question: `q${i}`, answer: `a${i}` }));
  const messages = buildQuestionMessages(baseVideoState, { spoilerFreeAnswers: true }, 'recap text', history, 'final question');
  // system, user(context), assistant(ack), then 10 turns * 2 messages, then the new question.
  assert.equal(messages.length, 3 + 20 + 1);
  const historyContents = messages.slice(3, -1).map((m) => m.content);
  assert.equal(historyContents.includes('q0'), false);
  assert.equal(historyContents.includes('q4'), false);
  assert.equal(historyContents.includes('q5'), true);
  assert.equal(historyContents.includes('q14'), true);
});

test('buildQuestionMessages: transcript appended to context when present', () => {
  const videoState = { ...baseVideoState, transcript: { text: '[0:01] specific transcript line' } };
  const messages = buildQuestionMessages(videoState, { spoilerFreeAnswers: true }, 'recap text', [], 'who is that?');
  const contextMessage = messages[1];
  assert.match(contextMessage.content, /specific transcript line/);
});

test('buildQuestionMessages: no transcript block when transcript is absent', () => {
  const messages = buildQuestionMessages(baseVideoState, { spoilerFreeAnswers: true }, 'recap text', [], 'who is that?');
  const contextMessage = messages[1];
  assert.doesNotMatch(contextMessage.content, /Caption transcript/);
});
