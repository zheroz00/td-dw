// Live caption capture for the DRM streaming sites (Netflix, Prime Video,
// Disney+). Those players never expose the subtitle file, but they do paint
// each cue into the DOM while it is on screen. A MutationObserver on that
// container turns the cues the viewer has already seen into a partial
// transcript: it covers "from when this tab loaded, while subtitles were on",
// not the whole title. The recap engine treats it as an anchor for the model's
// own knowledge (hybrid mode) rather than as a full transcript.
//
// Cue times are recorded as the <video>'s stream time and converted to real
// playback position at read time, because ad-stitched players (Disney+ ad
// tier) report stream time that includes ads. See getTranscriptUpTo.
globalThis.TDDW = globalThis.TDDW || { adapters: [] };

(() => {
  const MAX_CUES = 5000;
  const SCAN_INTERVAL_MS = 3000;
  // A cue re-shown within this window of its last sighting (rewind, or the
  // player re-rendering the same line) is a duplicate, not a new moment.
  const DUPLICATE_WINDOW_S = 5;

  function formatTimestamp(seconds) {
    const s = Math.max(0, Math.floor(seconds));
    const h = Math.floor(s / 3600);
    const m = Math.floor((s % 3600) / 60);
    const sec = String(s % 60).padStart(2, '0');
    return h > 0 ? `${h}:${String(m).padStart(2, '0')}:${sec}` : `${m}:${sec}`;
  }

  // Text nodes joined with spaces: textContent would glue the two lines of a
  // cue together ("Hello<br>world" -> "Helloworld").
  function readCueText(root) {
    const parts = [];
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
      const t = node.nodeValue.trim();
      if (t) parts.push(t);
    }
    return parts.join(' ').replace(/\s+/g, ' ').trim();
  }

  // Pure half of getTranscriptUpTo, kept separate so it can be unit-tested
  // without a DOM. `streamNow - nowReal` is the ad offset of the player right
  // now (zero on players without stitched ads); older cues were recorded before
  // any ads that ran since, so subtracting today's offset can only place them
  // earlier than they really were, never later. Erring early keeps a rewind
  // from surfacing a cue the viewer has not reached again.
  globalThis.TDDW.cuesToTranscript = function (cues, nowReal, streamNow, maxChars) {
    if (!cues.length || !Number.isFinite(nowReal)) return null;
    const offset = Number.isFinite(streamNow) ? streamNow - nowReal : 0;

    const timed = [];
    for (const cue of cues) {
      const t = cue.streamT - offset;
      if (t < 0 || t > nowReal + 1) continue;
      timed.push({ t, text: cue.text });
    }
    if (!timed.length) return null;
    timed.sort((a, b) => a.t - b.t);

    const lines = timed.map((c) => `[${formatTimestamp(c.t)}] ${c.text}`);
    const budget = maxChars || globalThis.TDDW.TRANSCRIPT_BUDGET_CHARS.standard;
    const { text, truncated } = globalThis.TDDW.capTranscript(lines, budget);
    return {
      text,
      language: null,
      autoGenerated: false,
      truncated,
      partial: true,
      coverageStartSeconds: timed[0].t,
      coverageEndSeconds: timed[timed.length - 1].t
    };
  };

  // { selectors, findVideo } -> { getTranscriptUpTo }
  //   selectors: candidate CSS selectors for the caption container, tried in
  //              order (light DOM first, then a shadow-DOM-piercing search).
  //   findVideo: () => HTMLVideoElement | null, the site's real player.
  globalThis.TDDW.startCaptionCapture = function ({ selectors, findVideo }) {
    let cues = []; // { streamT, text }
    let lastSeen = new Map(); // text -> streamT, for duplicate suppression
    let bufferKey = null; // location.pathname the cues belong to
    let bufferVideo = null; // the <video> the cues were timed against
    let observer = null;
    let observedRoot = null;
    let announced = false;

    function reset(reason) {
      if (cues.length) console.log(`[TD;DW] caption buffer reset (${reason})`);
      cues = [];
      lastSeen = new Map();
    }

    // A new title (episode autoplay, browsing to another watch page) means a
    // new buffer. Same pathname but a fresh <video> that restarted from the
    // top is treated the same way; a rewind on the same element is not.
    function syncBufferIdentity(video) {
      const key = location.pathname;
      if (key !== bufferKey) {
        reset('navigation');
        bufferKey = key;
      }
      if (video && video !== bufferVideo) {
        const last = cues[cues.length - 1];
        if (last && video.currentTime < last.streamT - 30) reset('new stream');
        bufferVideo = video;
      }
    }

    function record() {
      if (!observedRoot?.isConnected) return;
      const video = findVideo();
      if (!video) return;
      syncBufferIdentity(video);

      const text = readCueText(observedRoot);
      if (!text) return;
      const streamT = video.currentTime;
      const prev = lastSeen.get(text);
      if (prev !== undefined && Math.abs(prev - streamT) < DUPLICATE_WINDOW_S) return;
      lastSeen.set(text, streamT);

      cues.push({ streamT, text });
      if (cues.length > MAX_CUES) cues.splice(0, cues.length - MAX_CUES);
      if (!announced) {
        announced = true;
        console.log('[TD;DW] capturing captions from', observedRoot);
      }
    }

    function findContainer() {
      for (const sel of selectors) {
        const el = document.querySelector(sel);
        if (el) return el;
      }
      for (const sel of selectors) {
        const el = globalThis.TDDW.queryDeepAll(sel)[0];
        if (el) return el;
      }
      return null;
    }

    // The container only exists while captions are switched on, and Disney+
    // renders it inside shadow DOM, so poll for it and (re)attach as needed.
    function scan() {
      if (document.hidden) return;
      const root = findContainer();
      if (root === observedRoot && root?.isConnected) return;
      observer?.disconnect();
      observedRoot = root;
      if (!root) return;
      observer = new MutationObserver(record);
      observer.observe(root, { subtree: true, childList: true, characterData: true });
      record();
    }

    setInterval(scan, SCAN_INTERVAL_MS);
    scan();

    return {
      // Partial transcript of the cues shown at or before `nowReal` seconds of
      // playback. `video` is the player the caller read `nowReal` from; the
      // difference between its stream time and nowReal is the ad offset
      // (zero on players without stitched ads).
      //   -> { text, language, autoGenerated, truncated, partial, coverageStartSeconds, coverageEndSeconds } | null
      getTranscriptUpTo(nowReal, video, maxChars) {
        syncBufferIdentity(video || findVideo());
        const streamNow = Number.isFinite(video?.currentTime) ? video.currentTime : nowReal;
        return globalThis.TDDW.cuesToTranscript(cues, nowReal, streamNow, maxChars);
      }
    };
  };
})();
