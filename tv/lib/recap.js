import { randomUUID } from 'node:crypto';
import { pickProvider } from '../../background/providers/index.js';
import { buildQuestionMessages } from '../../background/providers/prompts.js';
import { chatCompletion } from '../../background/llm-client.js';
import { TICKS_PER_SECOND } from './jellyfin.js';
import { findNowPlaying } from './now-playing.js';
import { routeMedia } from './media-route.js';
import {
  parseJellyfinSubtitles,
  pickJellyfinSubtitleStream,
  capTranscript,
  TRANSCRIPT_BUDGET_CHARS
} from './shared.js';

// The extension's recap engine, unchanged: pickProvider sends a real transcript
// to the transcript provider and no transcript to memory mode. Injectable so
// tests never call a real LLM.
export const defaultEngine = {
  recap: (videoState, llm) => pickProvider(videoState, llm).getRecap(videoState, llm),
  answer: (messages, llm) => chatCompletion(llm, messages, { effort: 'medium' })
};

// The same videoState the browser's Jellyfin adapter builds, minus the transcript.
export function describeItem(item, positionSeconds) {
  const isEpisode = item.Type === 'Episode';
  return {
    service: 'Jellyfin',
    title: (isEpisode ? item.SeriesName : item.Name) || 'Unknown title',
    episodeInfo: isEpisode
      ? `S${item.ParentIndexNumber ?? '?'}:E${item.IndexNumber ?? '?'}${item.Name ? ` - ${item.Name}` : ''}`
      : null,
    currentTimeSeconds: positionSeconds,
    durationSeconds: item.RunTimeTicks ? item.RunTimeTicks / TICKS_PER_SECOND : null
  };
}

// The item's best text subtitle track, cut at the position and capped to the
// budget. Uses the media source that is actually playing, because a title
// with two versions numbers its streams differently. Returns null when there
// are only image subs (PGS/VOBSUB), no subs, or no cue before the position;
// the recap then comes from memory.
export async function loadTranscript(jellyfin, item, { mediaSourceId, positionSeconds, subtitleLang, transcriptBudget }) {
  const sources = item.MediaSources || [];
  const source = sources.find((s) => s.Id === mediaSourceId) || sources[0] || null;
  const streams = (source?.MediaStreams || item.MediaStreams || []).filter(
    (s) => s.Type === 'Subtitle' && s.IsTextSubtitleStream
  );
  const stream = pickJellyfinSubtitleStream(streams, subtitleLang);
  if (!stream) return null;

  const vtt = await jellyfin.getSubtitleVtt(item.Id, source?.Id || item.Id, stream.Index);
  const parsed = parseJellyfinSubtitles(vtt, positionSeconds * 1000, stream.Language);
  if (!parsed) return null;

  const budget = TRANSCRIPT_BUDGET_CHARS[transcriptBudget] || TRANSCRIPT_BUDGET_CHARS.standard;
  const { text, truncated } = capTranscript(parsed.lines, budget);
  return { text, language: parsed.language, autoGenerated: false, truncated };
}

const NO_ACCESS_NOTE =
  "The TD;DW Recap app doesn't have notification access, so it can only recap Jellyfin. See its README to turn it on.";

// Every path returns a record shaped like this, so the page and the store
// treat Jellyfin, YouTube and "not supported" recaps the same way.
function makeRecord({ videoState, result, fromResumePoint = false, subtitleNote = null }) {
  return {
    id: randomUUID(),
    createdAt: new Date().toISOString(),
    videoState,
    result,
    fromResumePoint,
    subtitleNote,
    history: []
  };
}

const notRecapped = (message) => ({ ok: true, known: false, message });

export function createRecapService({ jellyfin, youtube, config, engine = defaultEngine, log = console }) {
  async function recapJellyfin(hint) {
    const now = await findNowPlaying(jellyfin, config.jellyfin.device);

    if (now.sessionId && config.pauseOnRecap) {
      try {
        await jellyfin.pause(now.sessionId);
      } catch (err) {
        // Not worth failing the recap over; the viewer can pause by hand.
        log.warn(`[tv] could not pause the TV: ${err.message}`);
      }
    }

    const videoState = describeItem(now.item, now.positionSeconds);
    const notes = [];
    try {
      videoState.transcript = await loadTranscript(jellyfin, now.item, {
        mediaSourceId: now.mediaSourceId,
        positionSeconds: now.positionSeconds,
        subtitleLang: config.jellyfin.subtitleLang,
        transcriptBudget: config.llm.transcriptBudget
      });
    } catch (err) {
      // Fall back to memory mode, but say so on the page instead of quietly
      // handing over a less trustworthy recap.
      videoState.transcript = null;
      notes.push(`Couldn't load the subtitles (${err.message}), so this recap is from memory.`);
      log.warn(`[tv] subtitle load failed: ${err.message}`);
    }
    if (hint?.mediaAccess === false) notes.push(NO_ACCESS_NOTE);

    const result = await engine.recap(videoState, config.llm);
    return makeRecord({
      videoState,
      result,
      fromResumePoint: now.fromResumePoint,
      subtitleNote: notes.join(' ') || null
    });
  }

  // YouTube recaps come from captions only. A memory recap of a video that may
  // be a lookalike or a short clip would invent plot, so every miss says so
  // instead and the LLM is never called. The TV app pauses YouTube itself.
  async function recapYouTube({ title, artist, positionMs, durationMs }) {
    const videoState = {
      service: 'YouTube',
      title: title || 'YouTube',
      episodeInfo: artist || null,
      currentTimeSeconds: positionMs / 1000,
      durationSeconds: durationMs ? durationMs / 1000 : null
    };
    const done = (result) => makeRecord({ videoState, result });

    if (!title) {
      return done(notRecapped("YouTube didn't say what's playing. If an ad is showing, wait for it to finish and press again."));
    }

    try {
      const videoId = await youtube.findVideo(title, artist, videoState.durationSeconds);
      if (!videoId) {
        const by = artist ? ` by ${artist}` : '';
        return done(notRecapped(`Couldn't find "${title}"${by} on YouTube, so there's nothing to recap from.`));
      }

      const captions = await youtube.getTranscript(videoId, positionMs);
      if (!captions) {
        return done(notRecapped("TD;DW found no captions up to this point in the video, so there's nothing to recap yet."));
      }
      const budget = TRANSCRIPT_BUDGET_CHARS[config.llm.transcriptBudget] || TRANSCRIPT_BUDGET_CHARS.standard;
      const { text, truncated } = capTranscript(captions.lines, budget);
      videoState.transcript = { text, language: captions.language, autoGenerated: captions.autoGenerated, truncated };
    } catch (err) {
      log.warn(`[tv] YouTube lookup failed: ${err.message}`);
      return done({ ok: false, error: `Couldn't reach YouTube (${err.message}).` });
    }

    return done(await engine.recap(videoState, config.llm));
  }

  function recapUnsupported(name, { positionMs }) {
    const shown = name.charAt(0).toUpperCase() + name.slice(1);
    return makeRecord({
      videoState: {
        service: shown,
        title: shown,
        episodeInfo: null,
        currentTimeSeconds: positionMs / 1000,
        durationSeconds: null
      },
      result: notRecapped(`TD;DW on the TV doesn't support ${name} yet. It works with Jellyfin and YouTube.`)
    });
  }

  async function recap(hint = null) {
    const route = routeMedia(hint);
    if (route.kind === 'youtube') return recapYouTube(hint.nowPlaying);
    if (route.kind === 'unsupported') return recapUnsupported(route.name, hint.nowPlaying);
    return recapJellyfin(hint);
  }

  function ask(record, question) {
    const messages = buildQuestionMessages(
      record.videoState,
      config.llm,
      record.result.recapText,
      record.history,
      question
    );
    return engine.answer(messages, config.llm);
  }

  return { recap, ask };
}
