// YouTube side of TV recaps: find the video the TV app says is playing, then
// fetch its captions. Both use YouTube's unofficial InnerTube API (there is no
// official captions API for other people's videos), so either can break when
// YouTube changes it. Callers treat any error as "couldn't reach YouTube".
import { fetchYouTubeTranscript } from './shared.js';

const SEARCH_URL = 'https://www.youtube.com/youtubei/v1/search?prettyPrint=false';
const SEARCH_CONTEXT = { client: { clientName: 'WEB', clientVersion: '2.20250101.00.00', hl: 'en' } };
// The search filter "Type: Video", so channels, playlists and shorts shelves stay out.
const VIDEOS_ONLY = 'EgIQAQ==';

export class YouTubeError extends Error {
  constructor(message) {
    super(message);
    this.name = 'YouTubeError';
  }
}

// Case, spacing and Unicode compatibility forms (full-width letters, ligatures)
// don't make two strings different; anything else does.
export function normalize(text) {
  return String(text ?? '').normalize('NFKC').toLowerCase().replace(/\s+/g, ' ').trim();
}

// "12:34" or "1:02:03" to seconds; null for anything else (live streams have none).
function parseLength(text) {
  if (typeof text !== 'string' || !/^\d+(:\d{1,2}){1,2}$/.test(text)) return null;
  return text.split(':').reduce((total, part) => total * 60 + Number(part), 0);
}

const joinRuns = (title) => (title?.runs || []).map((run) => run.text).join('');

// Search results nest videoRenderer objects at varying depths and the layout
// changes now and then, so find them by name instead of by path.
export function collectVideos(node, found = []) {
  if (Array.isArray(node)) {
    for (const child of node) collectVideos(child, found);
  } else if (node && typeof node === 'object') {
    const video = node.videoRenderer;
    if (video?.videoId) {
      found.push({
        id: video.videoId,
        title: joinRuns(video.title),
        channel: video.ownerText?.runs?.[0]?.text || video.longBylineText?.runs?.[0]?.text || '',
        lengthSeconds: parseLength(video.lengthText?.simpleText)
      });
    }
    for (const child of Object.values(node)) collectVideos(child, found);
  }
  return found;
}

export function createYouTubeClient({
  fetchImpl = globalThis.fetch,
  fetchTranscript = fetchYouTubeTranscript,
  timeoutMs = 15000
} = {}) {
  const seconds = Math.round(timeoutMs / 1000);

  async function search(query) {
    let res;
    try {
      res = await fetchImpl(SEARCH_URL, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ context: SEARCH_CONTEXT, query, params: VIDEOS_ONLY }),
        signal: AbortSignal.timeout(timeoutMs)
      });
      if (!res.ok) throw new YouTubeError(`YouTube search failed (${res.status})`);
      return await res.json();
    } catch (err) {
      if (err instanceof YouTubeError) throw err;
      if (err.name === 'TimeoutError') throw new YouTubeError(`YouTube search timed out after ${seconds}s`);
      throw new YouTubeError(`YouTube search failed (${err.cause?.code ?? err.message})`);
    }
  }

  return {
    // The video id whose title AND channel both match exactly, or null. A
    // reupload elsewhere has the identical title, so a title match alone could
    // recap the wrong video; without a channel there is nothing to check.
    async findVideo(title, channel, durationSeconds) {
      const wantTitle = normalize(title);
      const wantChannel = normalize(channel);
      if (!wantTitle || !wantChannel) return null;

      const data = await search(`${title} ${channel}`);
      const matches = collectVideos(data).filter(
        (v) => normalize(v.title) === wantTitle && normalize(v.channel) === wantChannel
      );
      if (!matches.length) return null;

      const wantLength = Number.isFinite(durationSeconds) ? durationSeconds : null;
      if (wantLength === null) return matches[0].id;
      // Nearest length wins; a result with no length sorts last. Stable sort keeps result order on ties.
      const gap = (v) => (v.lengthSeconds === null ? Infinity : Math.abs(v.lengthSeconds - wantLength));
      return [...matches].sort((a, b) => gap(a) - gap(b))[0].id;
    },

    // { lines, language, autoGenerated } | null (no captions up to cutoffMs).
    // The caption fetch can't be aborted from here, so the timeout only stops
    // waiting for it.
    async getTranscript(videoId, cutoffMs) {
      let timer;
      const timeout = new Promise((_, reject) => {
        timer = setTimeout(() => reject(new YouTubeError(`YouTube captions timed out after ${seconds}s`)), timeoutMs);
      });
      try {
        return await Promise.race([Promise.resolve().then(() => fetchTranscript(videoId, cutoffMs)), timeout]);
      } finally {
        clearTimeout(timer);
      }
    }
  };
}
